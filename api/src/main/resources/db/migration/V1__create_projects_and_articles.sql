-- Projects: relational columns for what is queried, sorted or unique; the presentation
-- blocks (summary, details, seo) are always read and written whole, so they live in JSONB.
create table projects (
    id            bigint generated by default as identity primary key,
    slug          varchar(120) not null,
    status        varchar(16)  not null default 'DRAFT',
    display_order integer      not null,
    title         varchar(200) not null,
    category      varchar(200) not null,
    thumbnail     varchar(500) not null,
    logo          varchar(500),
    summary       jsonb        not null,
    details       jsonb        not null,
    seo           jsonb        not null,
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now(),
    constraint projects_slug_uk unique (slug),
    constraint projects_slug_format_ck check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    constraint projects_status_ck check (status in ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);

create index projects_status_order_idx on projects (status, display_order);

-- Articles: the Markdown frontmatter is flat, so every field is a column; the body stays
-- as raw Markdown and the site renders it.
create table articles (
    id            bigint generated by default as identity primary key,
    slug          varchar(120) not null,
    status        varchar(16)  not null default 'DRAFT',
    title         varchar(200) not null,
    description   varchar(500) not null,
    body_markdown text         not null,
    tags          text[]       not null default '{}',
    image         varchar(500),
    image_width   integer,
    image_height  integer,
    image_alt     varchar(300),
    published_on  date,
    revised_on    date,
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now(),
    constraint articles_slug_uk unique (slug),
    constraint articles_slug_format_ck check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    constraint articles_status_ck check (status in ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    constraint articles_image_size_ck check (image is null or (image_width > 0 and image_height > 0)),
    constraint articles_published_on_ck check (status <> 'PUBLISHED' or published_on is not null)
);

create index articles_status_published_on_idx on articles (status, published_on desc);
